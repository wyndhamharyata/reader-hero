// Writes src/domain/licences.ts: the licence of every component the app ships to the reader.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const modules = join(root, "node_modules");
const read = (...parts) => readFileSync(join(...parts), "utf8").trim();
const licenceText = (pkg) => {
  const file = readdirSync(join(modules, pkg)).find((entry) => /^licen[cs]e/i.test(entry));
  if (file === undefined) throw new Error(`No licence file in ${pkg}`);
  return read(modules, pkg, file);
};

// [npm package, the name the reader sees]
const packages = [
  ["@tanstack/react-virtual", "TanStack Virtual"],
  ["effect", "Effect"],
  ["fflate", "fflate"],
  ["idb", "idb"],
  ["pdfjs-dist", "PDF.js"],
  ["react", "React"],
  ["react-dom", "React DOM"],
  ["react-router", "React Router"],
  ["@fontsource-variable/atkinson-hyperlegible-mono", "Atkinson Hyperlegible Mono"],
  ["@fontsource-variable/atkinson-hyperlegible-next", "Atkinson Hyperlegible Next"],
  ["@fontsource-variable/literata", "Literata"],
];

// Hono runs on the worker, so it never reaches the reader; the fonts arrive as package files.
const shipped = Object.keys(JSON.parse(read(root, "package.json")).dependencies).filter(
  (name) => name !== "hono",
);
const listed = packages.map(([name]) => name);
const missing = shipped.filter((name) => !listed.includes(name));
if (missing.length > 0) throw new Error(`Add these to the licence list: ${missing.join(", ")}`);

const fromPackage = ([pkg, name]) => {
  const meta = JSON.parse(read(modules, pkg, "package.json"));
  return { name, version: meta.version, licence: meta.license, text: licenceText(pkg) };
};

const pdfjsVersion = JSON.parse(read(modules, "pdfjs-dist", "package.json")).version;
const decoder = (name, licence, files) => ({
  name,
  version: pdfjsVersion,
  licence,
  text: files.map((file) => read(modules, "pdfjs-dist", file)).join("\n\n"),
});

const entries = [
  ...packages.map(fromPackage),
  // The decoders and the colour profile ship as files in public/, with their own licences.
  decoder("JBIG2 decoder", "BSD-3-Clause, Apache-2.0", ["wasm/LICENSE_JBIG2", "wasm/LICENSE_PDFJS_JBIG2"]),
  decoder("OpenJPEG", "BSD-2-Clause", ["wasm/LICENSE_OPENJPEG", "wasm/LICENSE_PDFJS_OPENJPEG"]),
  decoder("qcms", "MIT", ["wasm/LICENSE_QCMS", "wasm/LICENSE_PDFJS_QCMS"]),
  decoder("ICC colour profile", "CC0-1.0", ["iccs/LICENSE"]),
  // The wordmark and the icons are set in Montserrat, converted to outlines.
  { name: "Montserrat ExtraBold", version: "", licence: "OFL-1.1", text: read(root, "scripts", "licences", "montserrat-OFL.txt") },
];

const source = [
  "// Generated by scripts/make-licences.mjs; run npm run licences to write it again.",
  `export const licences = ${JSON.stringify(entries, null, 2)};`,
  "",
].join("\n");
writeFileSync(join(root, "src", "domain", "licences.ts"), source);
console.log(`wrote ${entries.length} licences to src/domain/licences.ts`);
